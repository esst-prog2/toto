"""Permission-gated DFB transport and immutable, checksummed local response cache.

No network request occurs merely by importing/constructing these classes. Approval
files are operator-supplied evidence references, not a grant generated by software.
"""
from __future__ import annotations

from datetime import datetime, timezone
import hashlib
import json
import math
from pathlib import Path
import time
from urllib.error import HTTPError, URLError
from urllib.parse import urlsplit
from urllib.request import HTTPRedirectHandler, Request, build_opener


def digest(content):
    return hashlib.sha256(content).hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode()


def write_once(path, content):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        if path.read_bytes() != content:
            raise ValueError(f'Refusing to overwrite differing artifact: {path}')
        return
    # Atomic publication: a crash must never leave a partial "cached" response.
    import os
    import tempfile
    fd, temporary = tempfile.mkstemp(prefix='.dfb-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        try:
            os.link(temporary, path)
        except FileExistsError:
            if path.read_bytes() != content:
                raise ValueError(f'Concurrent artifact conflict: {path}')
    finally:
        os.unlink(temporary)


def allowed_url(url):
    import re
    u = urlsplit(url)
    return (u.scheme == 'https' and u.netloc == 'datencenter.dfb.de'
            and not u.query and not u.fragment
            and re.fullmatch(r'/de/competitions/bundesliga/seasons/\d{4}-\d{2,4}/matchday/\d+', u.path))


class AccessStopped(RuntimeError):
    """A policy, server or cache safety gate stopped acquisition."""


class ResponseCache:
    def __init__(self, root):
        self.root = Path(root)

    def event(self, **event):
        self.root.mkdir(parents=True, exist_ok=True)
        with (self.root / 'events.jsonl').open('a', encoding='utf-8') as handle:
            handle.write(json.dumps(dict(at=datetime.now(timezone.utc).isoformat(), **event), ensure_ascii=False) + '\n')
            handle.flush()

    def get(self, url):
        path = self.root / 'pages' / (digest(url.encode()) + '.json')
        if not path.exists():
            return None
        entry = json.loads(path.read_text())
        import re
        if not re.fullmatch(r'[0-9a-f]{64}', entry.get('sha256','')):
            raise AccessStopped('Invalid cached checksum identifier')
        if entry['url'] != url or entry['status'] != 200:
            raise AccessStopped('Invalid cached page identity/status')
        body_path = self.root / 'bodies' / (entry['sha256'] + '.html')
        content = body_path.read_bytes()
        if digest(content) != entry['sha256'] or len(content) != entry['bytes']:
            raise AccessStopped('Cached response checksum mismatch; do not re-download over it')
        return entry, content

    def store(self, url, content, *, retrieved_at, basis, reference, headers=None):
        if not allowed_url(url):
            raise ValueError('Only allowlisted DFB Bundesliga matchday URLs are supported')
        entry = dict(url=url, status=200, sha256=digest(content), bytes=len(content),
                     retrieved_at=retrieved_at, access_basis=basis, evidence_reference=reference,
                     headers=headers or {})
        old = self.get(url)
        if old:
            if old[1] != content:
                # Preserve the conflicting response too, never silently select a winner.
                write_once(self.root/'conflicts'/(entry['sha256']+'.html'), content)
                write_once(self.root/'conflicts'/(entry['sha256']+'.json'), json_bytes(entry))
                raise AccessStopped('Different snapshot for cached URL; explicit version review required')
            return old[0]
        write_once(self.root/'bodies'/(entry['sha256']+'.html'), content)
        write_once(self.root/'pages'/(digest(url.encode())+'.json'), json_bytes(entry))
        return entry


class _NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


def request_once(url):
    """One public request, identifiable agent, no redirects/cookies/credentials."""
    request = Request(url, headers={'User-Agent': 'TOTOdology-DFB-AuthorizedCollector/1.0', 'Accept': 'text/html'})
    try:
        with build_opener(_NoRedirect()).open(request, timeout=30) as response:
            return response.status, dict(response.headers), response.read(8_000_001)
    except HTTPError as exc:
        return exc.code, dict(exc.headers), exc.read(8_000_001)


def check_authorization(approval, url, now):
    """Fail closed; approved URLs and the supporting document must match exactly."""
    if not approval or approval.get('network_collection_authorized') is not True:
        raise AccessStopped('Written authorization is required before network collection')
    if not allowed_url(url) or url not in approval.get('approved_urls', []):
        raise AccessStopped('URL is outside the explicit authorized inventory')
    try:
        until = datetime.fromisoformat(approval['valid_until'])
        reviewed = datetime.fromisoformat(approval['conditions_reviewed_at'])
        if reviewed.tzinfo is None or until.tzinfo is None:
            raise ValueError('timezone required')
        reference = Path(approval['evidence_path'])
        content = reference.read_bytes()
        interval = float(approval['minimum_interval_seconds'])
        if not content or digest(content) != approval['evidence_sha256']:
            raise ValueError('permission document checksum differs')
        if not approval.get('permission_reference') or not math.isfinite(interval) or interval < 5:
            raise ValueError('invalid permission reference or interval (minimum five seconds)')
        if reviewed.timestamp() > now or now - reviewed.timestamp() > 7*86400:
            raise ValueError('access-condition review must be within the last seven days')
        if until.timestamp() <= now:
            raise ValueError('authorization expired')
    except (KeyError, ValueError, OSError, TypeError) as exc:
        raise AccessStopped(f'Invalid authorization evidence: {exc}') from exc
    return interval


class AuthorizedFetcher:
    def __init__(self, cache, approval=None, *, request=request_once, sleep=time.sleep, clock=time.time, retries=2):
        if not isinstance(retries, int) or not 0 <= retries <= 3:
            raise ValueError('retries must be between zero and three')
        self.cache, self.approval = cache, approval
        self.request, self.sleep, self.clock, self.retries = request, sleep, clock, retries

    def fetch(self, url):
        cached = self.cache.get(url)
        if cached:
            self.cache.event(action='cache_hit', url=url, sha256=cached[0]['sha256'])
            return cached
        interval = check_authorization(self.approval, url, self.clock())
        # One persistent lock and persisted request times also pace separate processes/runs.
        import fcntl
        self.cache.root.mkdir(parents=True, exist_ok=True)
        with (self.cache.root/'network.lock').open('a') as lock:
            try:
                fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as exc:
                raise AccessStopped('Another collector holds the network lock') from exc
            cached = self.cache.get(url)
            if cached:
                return cached
            if (self.cache.root/'STOP.json').exists():
                raise AccessStopped('Persistent server stop is active; operator review required')
            for attempt in range(self.retries+1):
                interval = check_authorization(self.approval, url, self.clock())
                previous = self.cache.root/'last_request.json'
                if previous.exists():
                    wait = json.loads(previous.read_text())['time'] + interval - self.clock()
                    if wait > 0:
                        self.sleep(wait)
                check_authorization(self.approval, url, self.clock())
                # Mutable scheduling state is separate from immutable source responses.
                from os import replace
                temporary = self.cache.root/'last_request.next'
                temporary.write_bytes(json_bytes(dict(time=self.clock())))
                replace(temporary, previous)
                self.cache.event(action='request', url=url, attempt=attempt+1)
                try:
                    status, headers, content = self.request(url)
                except (URLError, TimeoutError, OSError) as exc:
                    self.cache.event(action='transient_transport_error', url=url, error=type(exc).__name__)
                    if attempt == self.retries:
                        raise AccessStopped('Transient transport retries exhausted') from exc
                    self.sleep(interval * 2**attempt)
                    continue
                # Preserve all obtained bodies, including errors, before interpretation.
                stamp = datetime.now(timezone.utc).isoformat()
                sha = digest(content)
                clean_headers = {k:v for k,v in headers.items() if k.lower() not in ('set-cookie','authorization','proxy-authorization')}
                write_once(self.cache.root/'attempts'/(sha+'.html'), content)
                self.cache.event(action='response', url=url, status=status, sha256=sha,
                                 headers=clean_headers, retrieved_at=stamp)
                lower = content.decode('utf-8', errors='replace').lower()
                blocked = any(token in lower for token in ('cf-chl-', 'g-recaptcha', 'hcaptcha',
                          'verify you are human', 'captcha', 'access denied', 'zugriff verweigert', 'automated access is not allowed',
                          'automatisierte zugriffe sind nicht erlaubt', 'type="password"'))
                if status in (401,403,429,451) or blocked:
                    stop = dict(url=url, status=status, sha256=sha, reason='access restriction; no retry', at=stamp)
                    write_once(self.cache.root/'STOP.json', json_bytes(stop))
                    raise AccessStopped('Server access restriction; acquisition stopped without retry/bypass')
                retry_after = next((v for k,v in headers.items() if k.lower()=='retry-after'), None)
                if retry_after:
                    # Stop rather than retrying sooner than an indicated restriction.
                    write_once(self.cache.root/'STOP.json', json_bytes(dict(url=url,status=status,retry_after=retry_after)))
                    raise AccessStopped('Server supplied Retry-After; stop for operator scheduling review')
                if status in (500,502,503,504) and attempt < self.retries:
                    self.sleep(interval * 2**attempt)
                    continue
                if status != 200:
                    raise AccessStopped(f'HTTP {status}; no redirect following or archive continuation')
                if len(content) > 8_000_000:
                    raise AccessStopped('Unexpected response size; inspect cached attempt')
                from .dfb_html import parse_dfb_matchday
                parsed = parse_dfb_matchday(content.decode('utf-8'))  # reject login/unknown/empty layout
                if parsed.source_url != url:
                    raise AccessStopped('Response canonical URL differs from requested inventory URL')
                entry = self.cache.store(url, content, retrieved_at=stamp, basis='written_network_authorization',
                                         reference=self.approval['permission_reference'], headers=clean_headers)
                return entry, content
        raise AccessStopped('Retries exhausted')
